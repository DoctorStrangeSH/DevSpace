/*
 * Local editing mode, NOT authentication.
 * GitHub Pages has no trusted server session and cloud writes stay disabled.
 */
var AuthService = {
    _isOwner: false,
    _modeKey: 'devspace_local_edit_mode',

    init: function () {
        // Remove the legacy plain-text credential stored by earlier versions.
        try { localStorage.removeItem('devspace_auth_key'); } catch (_) {}
        try { this._isOwner = localStorage.getItem(this._modeKey) === 'enabled'; }
        catch (_) { this._isOwner = false; }
        this._updateUI();
    },

    login: function () {
        // Compatibility with older modules: enables browser-local editing only.
        this._isOwner = true;
        try { localStorage.setItem(this._modeKey, 'enabled'); } catch (_) {}
        this._updateUI();
        if (typeof NotificationModule !== 'undefined') {
            NotificationModule.info('Локальный режим редактирования включён. Изменения не публикуются в облако.');
        }
        if (typeof EventBus !== 'undefined') EventBus.emit('auth:login');
        return true;
    },

    logout: function () {
        this._isOwner = false;
        try { localStorage.removeItem(this._modeKey); } catch (_) {}
        this._updateUI();
        if (typeof EventBus !== 'undefined') EventBus.emit('auth:logout');
    },

    isOwner: function () { return this._isOwner; },

    _showLoginDialog: function () {
        // Kept for links generated by the older project-detail module.
        if (this._isOwner) return;
        if (confirm('Включить локальное редактирование?\n\nПравки сохраняются только в этом браузере. Это НЕ вход владельца. Для публикации изменений необходима отдельная защищённая авторизация.')) {
            this.login();
        }
    },

    _updateUI: function () {
        var self = this;
        var button = document.getElementById('authBtn');
        if (button) {
            button.innerHTML = this._isOwner ? '<i class="bi bi-pencil-square"></i>' : '<i class="bi bi-pencil"></i>';
            button.title = this._isOwner ? 'Выключить локальное редактирование' : 'Включить локальное редактирование';
            button.setAttribute('aria-label', button.title);
            button.style.color = this._isOwner ? '#a8d8bd' : '';
            button.onclick = this._isOwner ? function () { self.logout(); } : function () { self._showLoginDialog(); };
        }

        document.querySelectorAll('.owner-only, .sync-owner-only').forEach(function (el) {
            el.style.display = self._isOwner ? '' : 'none';
        });
        var newButton = document.getElementById('newProjectBtn');
        if (newButton) newButton.style.display = this._isOwner ? '' : 'none';
        var heroButton = document.getElementById('heroAddProjectBtn');
        if (heroButton) heroButton.style.display = this._isOwner ? '' : 'none';
    }
};

window.AuthService = AuthService;
