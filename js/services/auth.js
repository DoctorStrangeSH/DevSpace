/*
 * Local editing mode, NOT authentication.
 * GitHub Pages has no trusted server session and cloud writes stay disabled.
 */
var AuthService = {
    _isOwner: false,
    _modeKey: 'devspace_local_edit_mode',

    init: function () {
        // Remove the legacy plain-text credential stored by earlier versions.
        try { localStorage.removeItem('devspace_auth_key'); } catch (_) {}
        try { this._isOwner = localStorage.getItem(this._modeKey) === 'enabled'; }
        catch (_) { this._isOwner = false; }
        this._updateUI();
    },

    login: function () {
        // Compatibility with older modules: enables browser-local editing only.
        this._isOwner = true;
        try { localStorage.setItem(this._modeKey, 'enabled'); } catch (_) {}
        this._updateUI();
        if (typeof NotificationModule !== 'undefined') {
            NotificationModule.info('Локальный режим редактирования включён. Изменения не публикуются в облако.');
        }
        if (typeof EventBus !== 'undefined') EventBus.emit('auth:login');
        return true;
    },

    logout: function () {
        this._isOwner = false;
        try { localStorage.removeItem(this._modeKey); } catch (_) {}
        this._updateUI();
        if (typeof EventBus !== 'undefined') EventBus.emit('auth:logout');
    },

    isOwner: function () { return this._isOwner; },

    getActivityActor: function () {
        var identity = typeof FirebaseIdentityModule !== 'undefined' && FirebaseIdentityModule
            ? FirebaseIdentityModule._user : null;
        if (identity && typeof identity.uid === 'string' && identity.uid) {
            var displayName = typeof identity.displayName === 'string' && identity.displayName.trim()
                ? identity.displayName.trim().slice(0, 100)
                : (typeof identity.email === 'string' ? identity.email.slice(0, 100) : 'Пользователь Google');
            return {
                id: 'google:' + identity.uid,
                name: displayName,
                email: typeof identity.email === 'string' ? identity.email.slice(0, 160) : '',
                photoURL: typeof identity.photoURL === 'string' ? identity.photoURL.slice(0, 1000) : '',
                type: 'google'
            };
        }

        var deviceId = null;
        try {
            deviceId = localStorage.getItem('devspace_activity_device_id');
            if (!deviceId || !/^[a-zA-Z0-9_-]{12,80}$/.test(deviceId)) {
                deviceId = 'device-' + (window.crypto && typeof window.crypto.randomUUID === 'function'
                    ? window.crypto.randomUUID().replace(/-/g, '')
                    : Date.now().toString(36) + Math.random().toString(36).slice(2, 14));
                localStorage.setItem('devspace_activity_device_id', deviceId);
            }
        } catch (_) {
            deviceId = 'device-session';
        }
        return {
            id: deviceId,
            name: this._isOwner ? 'Локальный редактор' : 'Гость (локально)',
            email: '',
            photoURL: '',
            type: this._isOwner ? 'local-editor' : 'anonymous'
        };
    },

    _showLoginDialog: function () {
        // Kept for links generated by the older project-detail module.
        if (this._isOwner) return;
        if (confirm('Включить локальное редактирование?\n\nПравки сохраняются только в этом браузере. Это НЕ вход владельца. Для публикации изменений необходима отдельная защищённая авторизация.')) {
            this.login();
        }
    },

    _updateUI: function () {
        var self = this;
        var button = document.getElementById('authBtn');
        if (button) {
            button.innerHTML = this._isOwner
                ? '<i class="bi bi-pencil-square" aria-hidden="true"></i><span class="edit-mode-label">Правки: вкл.</span>'
                : '<i class="bi bi-pencil" aria-hidden="true"></i><span class="edit-mode-label">Правки</span>';
            button.title = this._isOwner ? 'Выключить локальные правки (не выход из Google)' : 'Включить локальные правки (не вход в Google)';
            button.setAttribute('aria-label', button.title);
            button.setAttribute('aria-pressed', String(this._isOwner));
            button.classList.toggle('is-editing', this._isOwner);
            button.style.color = this._isOwner ? '#a8d8bd' : '';
            button.onclick = this._isOwner ? function () { self.logout(); } : function () { self._showLoginDialog(); };
        }

        document.querySelectorAll('.owner-only, .sync-owner-only').forEach(function (el) {
            el.style.display = self._isOwner ? '' : 'none';
        });
        var newButton = document.getElementById('newProjectBtn');
        if (newButton) newButton.style.display = this._isOwner ? '' : 'none';
        var heroButton = document.getElementById('heroAddProjectBtn');
        if (heroButton) heroButton.style.display = this._isOwner ? '' : 'none';
    }
};

window.AuthService = AuthService;
